class MonitorRealtimeB3:
    def __init__(self, cesta: List[str], arquivo_log: str = "alertas_b3.json"):
        self.cesta = cesta
        self.arquivo_log = arquivo_log
        self.creator = SubAgenteCreator()
        self.reviewer = SubAgenteReviewer(GuardrailsAtuariais())

    def executar_ciclo(self):
        agora = datetime.now()
        hora_atual = agora.time()
        print(f"\n[{agora.strftime('%Y-%m-%d %H:%M:%S')}] Executando varredura em {len(self.cesta)} ativos da B3...")

        if not (HORA_INICIO_PREGAO <= hora_atual <= HORA_FIM_PREGAO):
            print(f"[*] AVISO: Fora do horário de negociação regular ({HORA_INICIO_PREGAO.strftime('%H:%M')} às {HORA_FIM_PREGAO.strftime('%H:%M')}).")

        oportunidades = []

        for ticker in self.cesta:
            df_d = baixar_serie(ticker, period="60d", interval="1d")
            df_60 = baixar_serie(ticker, period="10d", interval="60m")
            df_15 = baixar_serie(ticker, period="5d", interval="15m")

            if df_d.empty or df_60.empty or df_15.empty:
                continue

            proposta = self.creator.avaliar_ativo(ticker, df_d, df_60, df_15)
            if not proposta:
                continue

            auditoria = self.reviewer.auditar(proposta)
            if auditoria["aprovado"]:
                oportunidades.append(proposta)
                self.emitir_card_alerta(proposta)
                self.salvar_log_alerta(proposta)
            else:
                print(f"[VETO REVISOR] {ticker}: convergência técnica detectada, mas violou Quality Gates: {auditoria['vetos']}")

        if not oportunidades:
            print("[STATUS] Nenhuma nova oportunidade confirmada pelos Quality Gates no momento.")

    def emitir_card_alerta(self, p: PropostaTrade):
        print("\n" + "="*80)
        print(f"🚨 [ALERTA DE OPORTUNIDADE HOMOLOGADA] - {p.ticker_ativo}")
        print("="*80)
        print(f"  • Data/Hora do Sinal (15m):    {p.data_hora}")
        print(f"  • Preço do Ativo Subjacente:   R$ {p.preco_ativo:.2f}")
        print(f"  • Ordem Gatilho (Buy Stop):    R$ {p.gatilho_buy_stop:.2f}")
        print(f"  • Stop Loss Estrutural (60m):  R$ {p.stop_loss_macro:.2f} (Risco R = R$ {p.risco_r:.2f})")
        print(f"  • Alvo Técnico (+2.0R):        R$ {p.alvo_2r:.2f}")
        print(f"  ------------------------------------------------------------------------")
        print(f"  • Opção Sugerida (Call OTM):   {p.ticker_opcao_sugerida} (Strike ~R$ {p.strike_opcao:.2f})")
        print(f"  • Prêmio Referência de Entrada:R$ {p.premio_referencia:.2f} (Alvo de Saída: ~R$ 0,60)")
        print(f"  • Métricas das Gregas:         Delta: {p.delta_estimado:.2f} | Gamma: {p.gamma_estimado:.3f} | Theta: {p.theta_pct_estimado*100:.1f}%/dia")
        print(f"  • Prazo até Vencimento:        {p.dte_dias_uteis} dias úteis (DTE)")
        print(f"  • Auditoria do Revisor:        APROVADO (100% aderente aos Guardrails)")
        print("="*80 + "\n")

    def salvar_log_alerta(self, p: PropostaTrade):
        """Persiste o alerta em arquivo JSON local para histórico e auditoria contínua."""
        registro = asdict(p)
        try:
            with open(self.arquivo_log, "a", encoding="utf-8") as f:
                f.write(json.dumps(registro, ensure_ascii=False) + "\n")
        except Exception as e:
            print(f"[ERRO LOG] Não foi possível salvar log do alerta: {e}")

