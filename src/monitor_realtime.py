class SubAgenteCreator:
    """Sub-Agente Criador: Ingestão, convergência técnica e formulação da proposta."""

    def avaliar_ativo(self, ticker: str, df_d: pd.DataFrame, df_60: pd.DataFrame, df_15: pd.DataFrame) -> Optional[PropostaTrade]:
        # 1. Validação da Tela 1 (Diário consolidado até o dia anterior)
        df_d_ind = calcular_indicadores_diario(df_d)
        t1 = df_d_ind.iloc[-1]
        t1_ant = df_d_ind.iloc[-2]

        mare_alta = bool((float(t1['EMA9']) > float(t1['EMA21'])) and (float(t1['MACD_Hist']) > float(t1_ant['MACD_Hist'])))
        if not mare_alta:
            return None

        # 2. Validação da Tela 2 (Últimas 4 barras fechadas de 60m)
        df_60_ind = calcular_indicadores_60m(df_60)
        ultimas_60 = df_60_ind.tail(4)
        if not ultimas_60['T2_Valida'].any():
            return None

        # 3. Validação da Tela 3 (Price Action no último candle fechado de 15m)
        candle_15 = df_15.iloc[-1]
        candle_15_ant = df_15.iloc[-2] if len(df_15) >= 2 else None
        if not checar_price_action(candle_15, candle_15_ant):
            return None

        # Definição dos Parâmetros Homologados
        swing_low_60 = float(df_60_ind.iloc[-1]['Swing_Low'])
        gatilho_entrada = float(candle_15['High']) + 0.01
        stop_macro = swing_low_60 - 0.02
        risco_r = gatilho_entrada - stop_macro

        # Guardrail de amplitude do risco
        if risco_r < RISCO_MIN_REAIS or risco_r > (gatilho_entrada * RISCO_MAX_PCT):
            return None

        alvo_ativo = gatilho_entrada + PAYOFF_ALVO * risco_r
        ticker_call = determinar_ticker_opcao(ticker, alvo_ativo)

        return PropostaTrade(
            ticker_ativo=ticker,
            data_hora=df_15.index[-1].strftime("%Y-%m-%d %H:%M"),
            preco_ativo=float(candle_15['Close']),
            gatilho_buy_stop=round(gatilho_entrada, 2),
            stop_loss_macro=round(stop_macro, 2),
            alvo_2r=round(alvo_ativo, 2),
            risco_r=round(risco_r, 2),
            ticker_opcao_sugerida=ticker_call,
            strike_opcao=round(alvo_ativo, 2),
            premio_referencia=0.20,
            delta_estimado=0.22,
            gamma_estimado=0.065,
            theta_pct_estimado=0.035,
            dte_dias_uteis=18
        )

class SubAgenteReviewer:
    """Sub-Agente Revisor: Quality Gates atuariais e poder de veto autônomo."""

    def __init__(self, guardrails: GuardrailsAtuariais):
        self.guardrails = guardrails

    def auditar(self, proposta: PropostaTrade) -> Dict[str, Any]:
        vetos = []
        if not (self.guardrails.premio_min <= proposta.premio_referencia <= self.guardrails.premio_max):
            vetos.append(f"Prêmio fora da faixa [{self.guardrails.premio_min}, {self.guardrails.premio_max}]")
        if not (self.guardrails.delta_min <= proposta.delta_estimado <= self.guardrails.delta_max):
            vetos.append(f"Delta fora do intervalo [{self.guardrails.delta_min}, {self.guardrails.delta_max}]")
        if proposta.gamma_estimado < self.guardrails.gamma_min:
            vetos.append(f"Gamma insuficiente ({proposta.gamma_estimado} < {self.guardrails.gamma_min})")
        if proposta.theta_pct_estimado > self.guardrails.theta_pct_max:
            vetos.append(f"Theta diário ({proposta.theta_pct_estimado*100:.1f}%) excede limite de {self.guardrails.theta_pct_max*100:.1f}%")
        if proposta.dte_dias_uteis < self.guardrails.dte_min:
            vetos.append(f"DTE ({proposta.dte_dias_uteis}) inferior a {self.guardrails.dte_min} dias úteis")

        aprovado = (len(vetos) == 0)
        return {"aprovado": aprovado, "vetos": vetos}

