def baixar_serie(ticker: str, period: str, interval: str) -> pd.DataFrame:
    """Ingestão com normalização de colunas e fuso horário de Brasília."""
    df = yf.download(ticker, period=period, interval=interval, progress=False, auto_adjust=False)
    if isinstance(df.columns, pd.MultiIndex):
        df.columns = df.columns.get_level_values(0)
    df = df.dropna()
    if not df.empty and df.index.tz is not None:
        df.index = df.index.tz_convert('America/Sao_Paulo').tz_localize(None)
    return df

def calcular_indicadores_diario(df_d: pd.DataFrame) -> pd.DataFrame:
    df = df_d.copy()
    df['EMA9'] = df['Close'].ewm(span=9, adjust=False).mean()
    df['EMA21'] = df['Close'].ewm(span=21, adjust=False).mean()
    ema12 = df['Close'].ewm(span=12, adjust=False).mean()
    ema26 = df['Close'].ewm(span=26, adjust=False).mean()
    df['MACD'] = ema12 - ema26
    df['MACD_Signal'] = df['MACD'].ewm(span=9, adjust=False).mean()
    df['MACD_Hist'] = df['MACD'] - df['MACD_Signal']
    df['T1_Valida'] = (df['EMA9'] > df['EMA21']) & (df['MACD_Hist'] > df['MACD_Hist'].shift(1))
    return df

def calcular_indicadores_60m(df_60: pd.DataFrame) -> pd.DataFrame:
    df = df_60.copy()
    low_min = df['Low'].rolling(window=14).min()
    high_max = df['High'].rolling(window=14).max()
    fast_k = 100 * ((df['Close'] - low_min) / (high_max - low_min + 1e-9))
    df['Slow_K'] = fast_k.rolling(window=3).mean()
    df['Slow_D'] = df['Slow_K'].rolling(window=3).mean()

    # Fundo e Topo do Swing dos 60m para Fibo e Stop Macro
    df['Swing_High'] = df['High'].rolling(window=25).max()
    df['Swing_Low'] = df['Low'].rolling(window=25).min()
    amplitude = df['Swing_High'] - df['Swing_Low']
    df['Fibo_382'] = df['Swing_High'] - 0.382 * amplitude
    df['Fibo_618'] = df['Swing_High'] - 0.618 * amplitude

    na_zona_fibo = (df['Low'] <= df['Fibo_382'] * 1.005) & (df['High'] >= df['Fibo_618'] * 0.995)
    estocastico_favoravel = (df['Slow_K'] < 40) & (df['Slow_K'] >= df['Slow_D'])
    df['T2_Valida'] = na_zona_fibo & estocastico_favoravel
    return df

def checar_price_action(candle: pd.Series, candle_ant: Optional[pd.Series] = None) -> bool:
    c = float(candle['Close'])
    o = float(candle['Open'])
    h = float(candle['High'])
    l = float(candle['Low'])
    corpo = abs(c - o)
    sombra_inf = min(c, o) - l
    sombra_sup = h - max(c, o)

    # 1. Martelo / Pin Bar
    if (sombra_inf >= 1.5 * corpo) and (sombra_sup <= 0.5 * corpo) and (corpo > 0.01):
        return True
    # 2. Engolfo de Alta
    if candle_ant is not None:
        c_ant = float(candle_ant['Close'])
        o_ant = float(candle_ant['Open'])
        if (c_ant < o_ant) and (c > o) and (c >= o_ant) and (o <= c_ant):
            return True
    # 3. Rejeição de Fundo (fechamento no terço superior)
    amplitude = h - l
    if amplitude > 0.05 and (c - l) >= 0.65 * amplitude:
        return True
    return False

def determinar_ticker_opcao(ticker_ativo: str, preco_alvo: float) -> str:
    """Gera a sigla da opção de compra (Call) para o vencimento com DTE > 15."""
    hoje = datetime.now()
    # Se estivermos na segunda quinzena, projeta o vencimento para o próximo mês
    mes_vencimento = hoje.month if hoje.day <= 10 else (hoje.month % 12) + 1
    letra_venc = LETRAS_CALL.get(mes_vencimento, 'A')
    codigo_base = ticker_ativo[:4]
    strike_int = int(round(preco_alvo))
    return f"{codigo_base}{letra_venc}{strike_int}"

